import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(__dirname, '..')
const outputFile = resolve(projectRoot, 'public/config.ads.js')

const SOURCE_URL = 'http://www.wenming.cn/wmpy/xsdgygg/zgm/zgmpm/index.html#section1'
const REQUEST_HEADERS = {
  'user-agent': 'Mozilla/5.0 (compatible; OSH-AdSync/1.0; +https://github.com/)'
}

function stripTags(text) {
  return String(text || '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;|&#160;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/\s+/g, ' ')
    .trim()
}

function normalizeHref(href) {
  const raw = String(href || '').trim()
  if (!raw || raw.startsWith('#') || raw.startsWith('javascript:') || raw.startsWith('mailto:')) return ''
  try {
    return new URL(raw, SOURCE_URL).toString()
  } catch {
    return ''
  }
}

function extractLinks(html) {
  const matches = html.matchAll(/<a\b[^>]*href=["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/gi)
  const result = []
  const seen = new Set()

  for (const match of matches) {
    const href = normalizeHref(match[1])
    if (!href) continue
    if (!href.includes('wenming.cn')) continue
    if (!/\/wmpy\//.test(href)) continue

    const title = stripTags(match[2])
    if (title.length < 6 || title.length > 40) continue

    const key = `${title}::${href}`
    if (seen.has(key)) continue
    seen.add(key)
    result.push({ title, href })
  }

  return result.slice(0, 8)
}

function buildProviderHtml(links, fetchedAt) {
  const itemHtml = links
    .map((item) => (
      `<a href="${item.href}" target="_blank" rel="noopener noreferrer nofollow" style="display:block;text-decoration:none;border-radius:12px;padding:10px 12px;background:rgba(255,255,255,.76);border:1px solid rgba(59,130,246,.14);color:#1e3a8a;font-size:12px;line-height:1.6">${item.title}</a>`
    ))
    .join('')

  return `<div style='height:100%;min-height:320px;border-radius:18px;background:linear-gradient(145deg,#eff6ff,#ecfeff);padding:24px;box-sizing:border-box;font-family:Space Grotesk,Noto Sans SC,sans-serif;color:#1d4ed8;display:flex;flex-direction:column;justify-content:space-between'><div><div style='font-size:11px;letter-spacing:.18em;text-transform:uppercase;opacity:.76'>Auto Synced</div><h3 style='margin:12px 0 0;font-size:22px;line-height:1.25'>中国文明网公益广告精选</h3><p style='margin:10px 0 0;font-size:13px;line-height:1.7;color:#334155'>自动抓取公开素材页并更新，点击可查看原始公益广告内容。</p><div style='display:grid;gap:8px;margin-top:12px'>${itemHtml}</div></div><div style='font-size:11px;opacity:.72'>最近更新：${fetchedAt}（来源：文明网公开页面）</div></div>`
}

function buildRuntimeConfigScript({ links, fetchedAt }) {
  const html = buildProviderHtml(links, fetchedAt)
  return `// Auto-generated by scripts/sync-public-service-ads.mjs\n(function () {\n  var provider = {\n    id: 'home-html-wenming-auto',\n    platform: 'custom-html',\n    title: '文明网公益广告（自动更新）',\n    html: ${JSON.stringify(html)}\n  };\n\n  var cfg = window.APP_AD_CONFIG || {};\n  var slots = cfg.slots || {};\n  var home = slots.home || {};\n  var providers = Array.isArray(home.providers) ? home.providers : [];\n\n  providers = [provider].concat(providers.filter(function (item) {\n    return item && item.id !== provider.id;\n  }));\n\n  home.providers = providers;\n  home.rotateMs = Number(home.rotateMs) > 0 ? Number(home.rotateMs) : 4800;\n  slots.home = home;\n  cfg.slots = slots;\n  cfg.__autoUpdatedAt = ${JSON.stringify(fetchedAt)};\n  cfg.__autoSource = ${JSON.stringify(SOURCE_URL)};\n  window.APP_AD_CONFIG = cfg;\n})();\n`
}

async function fetchSourceHtml() {
  const resp = await fetch(SOURCE_URL, { headers: REQUEST_HEADERS })
  if (!resp.ok) throw new Error(`request failed: ${resp.status}`)
  return await resp.text()
}

async function main() {
  const fetchedAt = new Date().toISOString().replace('T', ' ').slice(0, 19)

  let links = []
  try {
    const html = await fetchSourceHtml()
    links = extractLinks(html)
  } catch (err) {
    console.warn('[ads-sync] fetch failed, fallback to source landing link:', err?.message || err)
  }

  if (links.length < 3) {
    links = [
      { title: '中国文明网公益广告专题入口', href: SOURCE_URL },
      { title: '中国文明网公益广告频道', href: 'http://www.wenming.cn/wmpy/' },
      { title: '中国文明网首页', href: 'http://www.wenming.cn/' }
    ]
  }

  const js = buildRuntimeConfigScript({ links, fetchedAt })
  await mkdir(dirname(outputFile), { recursive: true })
  await writeFile(outputFile, js, 'utf8')
  console.log(`[ads-sync] wrote ${outputFile} with ${links.length} links`)
}

main().catch((err) => {
  console.error('[ads-sync] fatal:', err)
  process.exit(1)
})
